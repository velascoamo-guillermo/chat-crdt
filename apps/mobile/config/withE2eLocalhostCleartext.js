// Config plugin: lets the Maestro e2e build (release config) reach apps/server
// over plain http on the test hosts, and nothing else.
//
// Release builds block cleartext HTTP; the e2e build talks to
// http://localhost:3001 (adb reverse) or 10.0.2.2. In the e2e build's prebuild
// (config/e2eBuildToken.js), this writes a release-source-set network security config that
// permits cleartext for those hosts only (the base config stays cleartext-off).
// Without it, prebuild removes those files again, and build-e2e.sh deletes them
// right after its build, so a production assembleRelease never picks them up.
// iOS needs nothing: Info.plist already has NSAllowsLocalNetworking.

/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require('fs');
const path = require('path');
const { isE2eBuild, readE2eBuildToken } = require('./e2eBuildToken');

const MARKER = 'chatcrdt-e2e-localhost-cleartext';
const NSC_NAME = 'e2e_network_security_config';
const CLEARTEXT_HOSTS = ['localhost', '127.0.0.1', '10.0.2.2'];

const releaseManifestXml = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${MARKER}: generated by apps/mobile/config/withE2eLocalhostCleartext.js
     for the Maestro e2e build only. Do not commit or hand-edit. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <application android:networkSecurityConfig="@xml/${NSC_NAME}" />
</manifest>
`;

const networkSecurityConfigXml = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${MARKER} -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
${CLEARTEXT_HOSTS.map((host) => `        <domain includeSubdomains="false">${host}</domain>`).join('\n')}
    </domain-config>
</network-security-config>
`;

const isOurs = (file) => fs.readFileSync(file, 'utf8').includes(MARKER);

/**
 * Write (e2e build) or remove (any other build) the release-only files under
 * `appDir` (android/app).
 * @param {string} appDir
 * @param {Readonly<Record<string, string | undefined>>} env
 * @param {string | null} e2eToken
 * @returns {'written' | 'removed' | 'untouched'}
 */
function syncE2eReleaseFiles(appDir, env, e2eToken) {
  const manifest = path.join(appDir, 'src/release/AndroidManifest.xml');
  const nsc = path.join(appDir, `src/release/res/xml/${NSC_NAME}.xml`);

  if (isE2eBuild(env, e2eToken)) {
    if (fs.existsSync(manifest) && !isOurs(manifest)) {
      throw new Error(
        `${manifest} exists and was not written by withE2eLocalhostCleartext. ` +
          'Remove it before building the e2e app (a hand-made release manifest ' +
          'may open cleartext to every host).',
      );
    }
    fs.mkdirSync(path.dirname(nsc), { recursive: true });
    fs.writeFileSync(manifest, releaseManifestXml());
    fs.writeFileSync(nsc, networkSecurityConfigXml());
    return 'written';
  }

  let removed = false;
  for (const file of [manifest, nsc]) {
    if (fs.existsSync(file) && isOurs(file)) {
      fs.rmSync(file);
      removed = true;
    }
  }
  return removed ? 'removed' : 'untouched';
}

const withE2eLocalhostCleartext = (config) => {
  const { withDangerousMod } = require('expo/config-plugins');
  return withDangerousMod(config, [
    'android',
    (modConfig) => {
      const { platformProjectRoot, projectRoot } = modConfig.modRequest;
      syncE2eReleaseFiles(
        path.join(platformProjectRoot, 'app'),
        process.env,
        readE2eBuildToken(projectRoot),
      );
      return modConfig;
    },
  ]);
};

module.exports = withE2eLocalhostCleartext;
module.exports.syncE2eReleaseFiles = syncE2eReleaseFiles;
