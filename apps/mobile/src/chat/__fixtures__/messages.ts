import type { MessageDto } from '@chat-crdt/shared';

export const ROOM = 'general';
export const ME = 'user-me';
export const ALICE = 'user-alice';
export const BOB = 'user-bob';
export const T0 = 1_760_000_000_000;
export const MINUTE = 60_000;

const USERNAMES: Readonly<Record<string, string>> = {
  [ME]: 'me',
  [ALICE]: 'alice',
  [BOB]: 'bob',
};

export function msg(id: string, userId: string, offsetMs: number, content = 'hello'): MessageDto {
  return {
    id,
    roomId: ROOM,
    userId,
    username: USERNAMES[userId] ?? userId,
    content,
    createdAt: T0 + offsetMs,
  };
}

